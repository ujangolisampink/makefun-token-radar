// Token Radar, model radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other genuine pre-token protocol the snapshot carries. A protocol is pre-token when its record
// carries no token (no market cap, no CoinGecko id, no symbol) AND it is not a wrapped, staked or
// bridged product of a token that already trades: the house's own watchlist rule, applied to the
// whole board, not just the watchlist. That is why the starter's top rows — WBTC, Binance staked
// ETH, bridges — are gone here: they are Bitcoin or ETH in another wrapper, not a protocol still
// waiting on a launch of its own. The rule uses only snapshot fields: category, name, chains.
//
// Implied value follows only from the snapshot's own figures, never from a hand-kept list of names:
//
//   base_multiple = clamp(0.25 * (1e9 / tvl_usd)^0.08, 0.18, 0.40)
//        A smaller protocol launches at a higher multiple of TVL than a giant one: the value
//        scales sublinearly with size, so the board is not a TVL table in disguise.
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) * 0.8
//        Seven-day momentum matters: a protocol growing fast is worth more than one shrinking.
//   maturity   = 0.55 + min(age_days, 1460) / 1460 * 0.75   (age unknown: 365 days)
//        How long it has run with no token: a large, long-lived protocol with no token has the
//        most pent-up launch value; a protocol listed a month ago has barely started.
//   breadth    = min(1 + 0.02 * (chains - 1), 1.10)
//        More chains is more surface: more users, more integrations, more to farm.
//   implied    = max(1, round(tvl_usd * base_multiple * growthMult * maturity * breadth))
//
// The dashboard recomputes every row from the same figures, so the page and board.json agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

